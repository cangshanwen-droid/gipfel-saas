def seed_all(db: Session):
    """只在空数据库时执行"""
    if db.query(ContractType).count() > 0:
        return

    # 合同类型
    for name, desc, color, order in CONTRACT_TYPES:
        db.add(ContractType(name=name, description=desc, color=color, sort_order=order))

    # 基建类型 + 就业率加成
    for (name,cat,bonus,pop_add,talent,price,land,revenue,happy,
         h_bonus,carbon,act_price,ratio,unit,desc) in INFRA_TYPES:
        mfee = round(price * 0.02)
        db.add(InfrastructureType(
            name=name, category=cat, default_land_area=land, unit=unit,
            description=desc, price=price, revenue_index=revenue,
            recommended_ratio=ratio, maintenance_fee=mfee,
            population_addition=pop_add, talent_addition=talent,
            happiness_index=happy, h_bonus=h_bonus,
            carbon_reduction=carbon, activation_price=act_price,
        ))
        db.add(InfraEmploymentBonus(item_name=name, bonus=bonus))

    # 区域
    for name, pop, talent, carbon, cap, rate in DEFAULT_REGIONS:
        db.add(Region(name=name, population=pop, talent_population=talent,
                       carbon_emissions=carbon, population_capacity=cap,
                       base_growth_rate=rate))

    # 公司
    for name, region, ctype, contact in DEFAULT_COMPANIES:
        db.add(Company(name=name, region=region, company_type=ctype, contact=contact))

    # 管理员
    db.add(User(username="admin", password=hash_password("admin"), role="admin"))

    db.commit()
